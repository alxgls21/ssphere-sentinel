#!/usr/bin/env python3
"""Regenerate requirements/server.txt: exact, hash-pinned server dependencies.

The Docker image installs this file with ``pip install --require-hashes`` so
every build gets the same, verified packages. Version ranges stay in
pyproject.toml; run this script after changing them or to pick up updates.

Usage, from the repository root (needs network access to PyPI):

    python scripts/update_server_requirements.py [--python-version 3.14]

Dependencies are resolved for Linux/CPython at the image's Python version.
Every published file of each pinned version is hashed in, so the lock
installs on any platform the image is built for (amd64, arm64).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "requirements" / "server.txt"
# Debian-based image (glibc); pip does not expand a manylinux tag to the older
# compatible ones, so list them.
PLATFORMS = ("manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64")
WHEEL_NAME = re.compile(r"^(?P<name>[^-]+)-(?P<version>[^-]+)-")


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def resolve(requirements: list[str], python_version: str) -> dict[str, str]:
    """Return {name: version} for the requirements and their dependencies."""
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            [
                sys.executable, "-m", "pip", "download",
                "--quiet", "--disable-pip-version-check",
                "--only-binary=:all:",
                *(arg for platform in PLATFORMS for arg in ("--platform", platform)),
                "--implementation", "cp",
                "--python-version", python_version,
                "--abi", f"cp{python_version.replace('.', '')}",
                "--abi", "abi3",
                "--abi", "none",
                "--dest", tmp,
                *requirements,
            ],
            check=True,
        )
        pins = {}
        for wheel in Path(tmp).glob("*.whl"):
            match = WHEEL_NAME.match(wheel.name)
            if match is None:
                raise SystemExit(f"unexpected wheel name: {wheel.name}")
            pins[canonical(match["name"])] = match["version"]
        return pins


def file_hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        release = json.load(response)
    return sorted({item["digests"]["sha256"] for item in release["urls"]})


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--python-version", default="3.14")
    args = parser.parse_args()

    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    pins = resolve(project["dependencies"], args.python_version)

    lines = [
        "# Exact, hash-pinned server dependencies for the Docker image.",
        "# Generated by scripts/update_server_requirements.py from pyproject.toml",
        f"# (Linux, CPython {args.python_version}). Do not edit by hand.",
        "",
    ]
    for name in sorted(pins):
        hashes = file_hashes(name, pins[name])
        lines.append(f"{name}=={pins[name]} \\")
        lines.extend(f"    --hash=sha256:{digest} \\" for digest in hashes[:-1])
        lines.append(f"    --hash=sha256:{hashes[-1]}")
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(pins)} packages")


if __name__ == "__main__":
    main()
